def calculate_piston_position(temperature):
    """
    Рассчитываем высоту поршня в зависимости от температуры.
    Чем выше T, тем меньше Y (поршень выше, так как Y растет вниз).
    """
    # Простая линейная зависимость для визуализации
    # При T=100 поршень внизу (Y=400), при T=500 поршень вверху (Y=150)
    
    min_y = 150 # Верхнее положение
    max_y = 400 # Нижнее положение
    
    # Нормализуем температуру от 100 до 500 в диапазон от 1 до 0
    ratio = (temperature - 100) / (500 - 100) 
    
    # Считаем позицию Y (чем больше ratio, тем меньше Y)
    position = max_y - (max_y - min_y) * ratio
    return position
